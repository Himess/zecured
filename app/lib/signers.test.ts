// ------------------------------------------------------------------ checking a vault

/** Five signer keys and a production build that pins them. */
const KEYS = Array.from({ length: 5 }, () => generatePrivateKey());
const SIGNERS = KEYS.map((k) => privateKeyToAccount(k).address);
const PINNED = buildConfig({ ...DRY_RUN_ENV, NEXT_PUBLIC_SIGNERS: SIGNERS.join(",") });
const PINNED_REGISTRY = DRY_RUN_ENV.NEXT_PUBLIC_REGISTRY;

async function signAll(fields: VaultOpenedFields, keys: readonly Hex[] = KEYS): Promise<VaultSignature[]> {
  const typedData = vaultOpenedTypedData(PINNED_REGISTRY, vaultOpenedMessage(fields));
  return Promise.all(keys.map(async (k, i) => ({ index: i + 1, signature: await privateKeyToAccount(k).signTypedData(typedData) })));
}

const FIELDS: VaultOpenedFields = { ...VECTOR, ufvkHash: textHash(VECTOR_UFVK) };

async function refusal(fields: VaultOpenedFields, signatures: VaultSignature[]): Promise<unknown> {
  return verifyVaultOpened(fields, signatures, { config: PINNED }).then(
    () => "accepted",
    (e: unknown) => e,
  );
}

describe("verifyVaultOpened: every pinned signer must vouch for the vault", () => {
  it("accepts all five signatures of the pinned set, in any order", async () => {
    expect(PINNED).toMatchObject({ signersPinned: true, development: false, problems: [] });
    const signatures = await signAll(FIELDS);
    expect(await verifyVaultOpened(FIELDS, signatures, { config: PINNED })).toBe("pinned");
    expect(await verifyVaultOpened(FIELDS, [...signatures].reverse(), { config: PINNED })).toBe("pinned");
  });

  it("refuses the backend's own address or viewing key, and anything else not signed", async () => {
    const signatures = await signAll(FIELDS);
    const forged: Partial<VaultOpenedFields>[] = [
      { address: "utest1attacker" },
      { ufvkHash: textHash("uviewtest1attacker") },
      { expiryHeight: FIELDS.expiryHeight + 1 },
      { amount: 5_000_000n },
      { owner: "0x9999999999999999999999999999999999999999" },
      { account: "0x9999999999999999999999999999999999999999" },
      { vaultId: `0x${"66".repeat(32)}` },
    ];
    for (const patch of forged) {
      expect(await refusal({ ...FIELDS, ...patch }, signatures), JSON.stringify(Object.keys(patch))).toBeInstanceOf(VaultProofError);
    }
    // The right values under another Registry's domain.
    await expect(verifyVaultOpened(FIELDS, signatures, { config: PINNED, registry: REGISTRY })).rejects.toBeInstanceOf(VaultProofError);
  });

  it("refuses four signatures, a duplicate, a stranger's, or a malformed one", async () => {
    const signatures = await signAll(FIELDS);
    expect(await refusal(FIELDS, signatures.slice(1))).toBeInstanceOf(VaultProofError);
    expect(await refusal(FIELDS, [...signatures.slice(1), signatures[1]!])).toBeInstanceOf(VaultProofError);
    const stranger = await signAll(FIELDS, [...KEYS.slice(1), generatePrivateKey()]);
    expect(await refusal(FIELDS, stranger)).toBeInstanceOf(VaultProofError);
    // The backend's own five keys: a perfectly consistent, but unpinned, signer set.
    const backendKeys = Array.from({ length: 5 }, () => generatePrivateKey());
    expect(await refusal(FIELDS, await signAll(FIELDS, backendKeys))).toBeInstanceOf(VaultProofError);
    const malformed = [...signatures.slice(1), { index: 1, signature: `0x${"00".repeat(65)}` as Hex }];
    expect(await refusal(FIELDS, malformed)).toBeInstanceOf(VaultProofError);
    expect(await refusal(FIELDS, [])).toBeInstanceOf(VaultProofError);
  });
});

describe("which signer set (never the backend's in production)", () => {
  const DEV = { NODE_ENV: "development", NEXT_PUBLIC_BACKEND_URL: DRY_RUN_ENV.NEXT_PUBLIC_BACKEND_URL };
  const UNPINNED_ENV = { ...DRY_RUN_ENV, NEXT_PUBLIC_SIGNERS: undefined };
  const backendReports = (signers: Address[] | null): RemoteConfig => ({
    chainId: 84532,
    registry: PINNED_REGISTRY,
    adapter: DRY_RUN_ENV.NEXT_PUBLIC_ADAPTER,
    contracts: null,
    market: null,
    signers,
    denominations: [1_000_000n],
    confirmations: 3,
    vaultExpiryBlocks: 288,
    sponsorship: false,
  });

  it("a production build without NEXT_PUBLIC_SIGNERS refuses, even with the backend's set", async () => {
    const c = buildConfig(UNPINNED_ENV, backendReports(SIGNERS));
    expect(c.signers).toBeNull();
    expect(() => signerSet(c)).toThrow(VaultProofError);
    expect(vaultCheckUnavailable(c)).toMatch(/NEXT_PUBLIC_SIGNERS/);
    await expect(verifyVaultOpened(FIELDS, await signAll(FIELDS), { config: c })).rejects.toBeInstanceOf(VaultProofError);
    expect(vaultCheckUnavailable(PINNED)).toBeNull();
  });

  it("a development build falls back to the backend's set, marked as such, or to no check", async () => {
    const withSet = buildConfig(DEV, backendReports(SIGNERS));
    expect(withSet).toMatchObject({ development: true, signersPinned: false });
    expect(signerSet(withSet).check).toBe("backend");
    expect(await verifyVaultOpened(FIELDS, await signAll(FIELDS), { config: withSet })).toBe("backend");
    // Still refused when the backend's own set does not sign.
    const stranger = await signAll(FIELDS, [...KEYS.slice(1), generatePrivateKey()]);
    await expect(verifyVaultOpened(FIELDS, stranger, { config: withSet })).rejects.toBeInstanceOf(VaultProofError);

    const none = buildConfig(DEV, backendReports(null));
    expect(await verifyVaultOpened(FIELDS, [], { config: none })).toBe("unchecked");
    // A development build with the pin checks against the pin.
    const pinnedDev = buildConfig({ ...DEV, NEXT_PUBLIC_SIGNERS: SIGNERS.join(",") }, backendReports(SIGNERS));
    expect(signerSet(pinnedDev).check).toBe("pinned");
  });
});

describe("storedVault", () => {
  it("is null for loans without a vault or opened before vaults were signed", async () => {
    const loan = createLoan(1_000_000n);
    expect(storedVault(loan)).toBeNull();
    const legacy = { ...loan, vaultId: VECTOR.vaultId, vaultAddress: VECTOR_ADDRESS, expiryHeight: 4_486_288 };
    expect(storedVault(legacy)).toBeNull();
    const signatures = await signAll(FIELDS);
    const signed = { ...legacy, ufvkHash: FIELDS.ufvkHash, vaultSignatures: signatures };
    expect(storedVault(signed)).toEqual({
      fields: { ...FIELDS, owner: loan.owner, account: loan.account },
      signatures,
    });
  });
});
