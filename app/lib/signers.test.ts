    expect(textHash(VECTOR_ADDRESS)).toBe("0x4871c7074d79798b7991d7f71f57e723823958fec9d143805fd5127ccfa55f59");
    expect(textHash(VECTOR_UFVK)).toBe(VECTOR.ufvkHash);
    // Never as hex, whatever the string looks like.
