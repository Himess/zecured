#!/usr/bin/env bash
# Fetch reference sources into docs/ref/vendor/ (gitignored) so that code is written
# against the real, current APIs (Ironwood / NU7 post-date most model training data).
# Usage: scripts/fetch-refs.sh            # clone missing repos
#        scripts/fetch-refs.sh --update   # also fast-forward existing clones
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENDOR="$ROOT/docs/ref/vendor"
mkdir -p "$VENDOR"

REPOS=(
  "zcash/librustzcash"            # zcash_primitives, zcash_protocol, zcash_keys, zcash_address, pczt, zip321, client_backend
  "zcash/orchard"                 # Orchard / Ironwood actions, keys, builder
  "zcash/zips"                    # ZIP-316, ZIP-317, ZIP-321, Ironwood / NU7 ZIPs
  "zcash/zcash-devtool"           # reference wallet CLI incl. PCZT flows
  "zcash/incrementalmerkletree"   # incrementalmerkletree, shardtree (witnesses)
  "ZcashFoundation/frost"         # frost-core, frost-rerandomized
  "ZcashFoundation/reddsa"        # RedPallas + FROST ciphersuite
  "ZcashFoundation/frost-zcash-demo"  # frost-client, frostd, zcash-sign
  "morpho-org/morpho-blue"        # Morpho Blue core + callbacks
)

for repo in "${REPOS[@]}"; do
  name="${repo#*/}"
  dir="$VENDOR/$name"
  if [[ -d "$dir/.git" ]]; then
    if [[ "${1:-}" == "--update" ]]; then
      echo "updating $repo"; git -C "$dir" pull --ff-only --depth 1 -q || echo "  (update failed, keeping old clone)"
    else
      echo "have $repo ($(git -C "$dir" log -1 --format=%cs))"
    fi
  else
    echo "cloning $repo"
    git clone -q --depth 1 "https://github.com/$repo.git" "$dir"
  fi
done

{
  echo "# Vendored reference sources (generated by scripts/fetch-refs.sh)"
  echo
  echo "| Repo | Commit | Date |"
  echo "|---|---|---|"
  for repo in "${REPOS[@]}"; do
    dir="$VENDOR/${repo#*/}"
    echo "| $repo | $(git -C "$dir" rev-parse --short HEAD) | $(git -C "$dir" log -1 --format=%cs) |"
  done
} > "$ROOT/docs/ref/VENDORED.md"
echo "done -> docs/ref/VENDORED.md"
